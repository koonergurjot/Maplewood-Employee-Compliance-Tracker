-- Supabase schema for Maplewood Employee Compliance Tracker cloud sync
-- Tables
create extension if not exists "uuid-ossp";

create table if not exists public.employees (
  id uuid primary key default uuid_generate_v4(),
  payload jsonb not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.employee_requirements (
  id uuid primary key default uuid_generate_v4(),
  employee_id uuid not null references public.employees(id) on delete cascade,
  payload jsonb not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.imports (
  id uuid primary key default uuid_generate_v4(),
  status text not null check (status in ('pending', 'approved')),
  mode text not null default 'employees',
  file_name text,
  requested_by text,
  approved_by text,
  summary jsonb,
  mapping jsonb,
  header_row jsonb,
  row_count integer not null default 0,
  approved_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.import_rows (
  id bigint generated by default as identity primary key,
  import_id uuid not null references public.imports(id) on delete cascade,
  ordinal integer not null,
  raw jsonb,
  mapped jsonb,
  created_at timestamptz not null default timezone('utc', now())
);

-- Updated at trigger
create or replace function public.touch_updated_at()
returns trigger as
$$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$ language plpgsql;

create trigger trg_employees_touch_updated
  before update on public.employees
  for each row execute function public.touch_updated_at();

create trigger trg_employee_requirements_touch_updated
  before update on public.employee_requirements
  for each row execute function public.touch_updated_at();

create trigger trg_imports_touch_updated
  before update on public.imports
  for each row execute function public.touch_updated_at();

